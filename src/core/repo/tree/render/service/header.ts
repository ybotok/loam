/**
 * The one line that says a file under `architecture/` is LOAM'S — the opening
 * comment both generated views files carry, and the predicate that reads it
 * back off a file on disk.
 *
 * WHY A MARK EXISTS AT ALL. `architecture/subsystems.likec4` and
 * `architecture/services.likec4` are filenames loam RESERVES inside a directory
 * the team owns, and `loam subsystem sync` rewrites them wholesale. A docs repo
 * that already kept a hand-authored diagram at one of those paths — plausible
 * for `services.likec4` in particular, which loam reserved only now — would
 * have lost it on the first sync after the upgrade, with no warning and nothing
 * to restore it from. That is the one promise the rest of the tree keeps
 * everywhere: authored bytes stay authored, which is what archive's verbatim
 * splice is for. So the writer asks the file itself who wrote it, and refuses
 * every path where the answer is not loam.
 *
 * IT LIVES HERE, in the leaf package, for the reason `./view-id.ts` does: the
 * parent (`../views.ts`) may import a child and never the reverse, so the one
 * spelling BOTH generated files must open with has to sit below both. Two
 * literals for one mark is how the day comes that a file loam wrote is not
 * recognised as loam's and the writer refuses to regenerate its own output.
 *
 * SO DOES THE READ, AND SO DOES THE SENTENCE, and that is the correction this
 * module carries. The guard first shipped inside `loam subsystem sync` alone,
 * and there are FOUR other writers of exactly these two paths: the shared commit
 * window behind `subsystem new`, `rm`, `move` and `rename`
 * (`commands/subsystem/txn/txn.ts`) and `loam seed`
 * (`commands/seed/plan.ts`). Reproduced before this module grew: with a
 * hand-authored `architecture/services.likec4` in the tree, `loam subsystem new
 * platform` printed "architecture/services.likec4 updated" and destroyed it —
 * the file's digest changed and its first line became loam's header. A guard
 * that lives in one of five writers is not a guard. So the reader
 * (`readGeneratedFile`, `authoredGeneratedPaths`) and the refusal sentence
 * (`authoredRefusal`) sit beside the mark itself, below every writer, and a
 * sixth writer added tomorrow has one place to reach for rather than a fourth
 * spelling to invent.
 */
import { existsSync } from "node:fs";
import { readFile } from "node:fs/promises";

/**
 * The first bytes of every generated views file. Part of the content-compare
 * contract, so it is not prose that may be reworded: the rest of each header is,
 * and deliberately, because only this much identifies the owner.
 */
export const GENERATED_MARK = "// generated by loam";

/**
 * Was the text now at a generated path written by loam?
 *
 * A LEADING BYTE-ORDER MARK is stripped first, and that is not tidiness: a
 * Windows editor that opens a generated file and saves it back adds one without
 * changing a single fact in the file, and without this the writer would call its
 * own output authored and refuse to regenerate it for good — a refusal no
 * re-running could ever clear. CRLF needs no such treatment, for the reason
 * `viewsAgree` records one file over: the mark is the head of the first line and
 * the line ending is behind it.
 *
 * The test is the MARK and not the whole header, because the header's remaining
 * lines differ between the two files and are prose. It is also deliberately not
 * a test of the whole file: a hand EDIT of a generated file keeps the header, and
 * that file is loam's to repair — `subsystem.views-stale` names it and one sync
 * puts it back. Only a file that never carried the mark is somebody else's.
 */
export function isGenerated(text: string): boolean {
  return text.replace(/^\uFEFF/, "").startsWith(GENERATED_MARK);
}

/** What a writer of a generated path learns by reading it, in one read. */
export interface GeneratedFileRead {
  /** The bytes as text, or null when nothing stands at the path. */
  text: string | null;
  /** SOMEBODY ELSE wrote this: a file is there and its first line is not the mark. */
  authored: boolean;
}

/**
 * Read one generated path and answer both questions about it at once \u2014 what it
 * says, and whether loam may write it.
 *
 * ONE READ, because the only caller that needs the text is the one that also
 * compares it (`subsystem sync`'s `planFile`), and asking the disk twice for the
 * same small file so that two helpers could each own half the answer is how the
 * two halves come to disagree about which file they were talking about.
 *
 * ABSENT IS NOT AUTHORED. There is nothing to lose at a path that holds
 * nothing, and a fleet being scaffolded must still get its first generated file
 * \u2014 a guard that refused an absent file would refuse every repository forever.
 */
export async function readGeneratedFile(path: string): Promise<GeneratedFileRead> {
  if (!existsSync(path)) return { text: null, authored: false };
  const text = await readFile(path, "utf8");
  return { text, authored: !isGenerated(text) };
}

/**
 * Which of these generated paths hold a file loam did not write \u2014 the question
 * every writer that rewrites the PAIR wholesale asks before it stages anything.
 *
 * The paths come back in the order they were given, so a caller's message names
 * the files in a stable order rather than in whichever order the reads finished.
 */
export async function authoredGeneratedPaths(paths: readonly string[]): Promise<string[]> {
  // Independent reads of at most two small files: `Promise.all`, per the house
  // rule, and the order of the input is preserved by the map rather than by the
  // scheduler.
  const reads = await Promise.all(
    paths.map(async (path) => ({ path, read: await readGeneratedFile(path) })),
  );
  return reads.filter((r) => r.read.authored).map((r) => r.path);
}

/**
 * The one sentence a refusal owes about ONE authored file, composed here and
 * parameterised by the file, because FIVE writers refuse for this reason and a
 * reader who met the sentence from `loam subsystem sync` must recognise it
 * verbatim from `loam subsystem new`, `rm`, `move`, `rename` and `loam seed`.
 *
 * It names three things a person cannot get anywhere else: which file was left
 * alone, WHY loam thinks the file is not its own (the mark it looked for), and
 * the fact that nothing was written to it. The last clause closes the loop the
 * refusal otherwise leaves open \u2014 `loam validate --all` will keep reporting
 * `subsystem.views-stale` for that path and keep naming `loam subsystem sync` as
 * the repair, so a person who is not told why the writers decline would be sent
 * back and forth between the two forever.
 *
 * It deliberately does NOT name a command to re-run. It used to say "re-run
 * `loam subsystem sync`", which was true of the one caller it then had and wrong
 * for the four that were added: the command to re-run is the one the person
 * typed, and the sentence a caller appends says what that command did instead.
 */
export function authoredRefusal(file: string): string {
  return (
    `${file} left as it is \u2014 its first line is not \`${GENERATED_MARK}\`, so it is an AUTHORED file standing at a ` +
    "path loam generates and rewrites wholesale. Nothing was written to it and not one of its bytes changed. " +
    "Rename it to something loam does not reserve (every other `.likec4` under architecture/ renders in the same " +
    "project, so the diagram is not lost) or delete it, then re-run. Until then `loam validate --all` reports " +
    "`subsystem.views-stale` for that path and every loam command that writes the file keeps refusing."
  );
}
