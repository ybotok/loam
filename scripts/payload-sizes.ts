/**
 * docs/BENCHMARKS.md's agent-facing payload table, measured rather than typed.
 *
 * The cost of loam to an agent is the bytes it is handed: the generated
 * AGENTS.md, the adopt brief, each `loam instructions` page and each
 * `loam explain` answer. Those numbers used to live only in prose ("54,833
 * bytes to 20,062", "from 120,896 bytes to 109,399"), each true on the day it
 * was typed and unchecked after, while every edit to a fix table or a protocol
 * moved them. An evaluator could reproduce the cost in a minute; nothing in
 * the repository could say whether a published figure was still the binary's.
 * So the table is generated here, and test/docs-facts.test.ts regenerates it
 * and fails when the committed block differs — the same discipline the rest of
 * that file applies to every other derivable fact in public prose.
 *
 * Measured IN PROCESS, through the same `buildProgram()` the binary runs, with
 * `console.log` captured — not by spawning the built CLI. That is what lets the
 * pin run inside the suite without a build and in seconds rather than minutes
 * (some three hundred `explain` invocations). It counts what a real process
 * would write: every loam command prints through `console.log` (core never
 * prints, and nothing in src/ writes to process.stdout directly), so stdout is
 * each call's formatted text plus its newline, which is how the bytes are
 * summed below. Byte counts were cross-checked against `node dist/cli.js … |
 * wc -c` when this script was written.
 *
 * Two normalisations, and they are the only ones: the adopt brief (and the
 * context pack) echoes the docs repo's ABSOLUTE path (`docsDir`), which is
 * different on every machine — it is counted as {@link DOCS_PLACEHOLDER} — and
 * the implementer briefs, the one row family that quotes the fleet's FILES, run
 * against an LF copy of it ({@link lfFleet}), because a Windows checkout holds
 * those files with CRLF. Both so the table is a fact about this tree rather than
 * about the checkout that measured it.
 *
 *   npx tsx scripts/payload-sizes.ts           print the block
 *   npx tsx scripts/payload-sizes.ts --write   rewrite it in docs/BENCHMARKS.md
 *   npx tsx scripts/payload-sizes.ts --check   exit 1 if the page is behind
 */
import { isUtf8 } from "node:buffer";
import { realpathSync } from "node:fs";
import { cp, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "node:util";
import { buildProgram } from "../src/cli.js";
import { AGENTS_MD } from "../src/core/agent/agents-md.js";
import { LOAM_VERSION } from "../src/core/envelope/version.js";

const ROOT = join(import.meta.dirname, "..");
const FLEET = join(ROOT, "examples", "docs");
const PAGE = join(ROOT, "docs", "BENCHMARKS.md");
export const BEGIN = "<!-- payload-sizes:begin — generated by scripts/payload-sizes.ts; do not edit by hand -->";
export const END = "<!-- payload-sizes:end -->";
const DATE_LINE = /^Measured \d{4}-\d{2}-\d{2} by `npx tsx scripts\/payload-sizes\.ts --write`\.$/m;
/** What the brief's absolute docsDir is counted as — see the module comment. */
const DOCS_PLACEHOLDER = "/work/docs";
/** The example fleet's service the README's adopt figures have always named. */
const SERVICE = "payment-service";

/**
 * One captured invocation: what stdout would carry, and the exit code. A run
 * that exits non-zero measured a refusal, not the payload, and is rejected by
 * {@link bytesOf} rather than tabulated.
 */
interface Captured {
  stdout: string;
  code: number;
}

/**
 * Run one loam invocation in process from the example fleet, and return the
 * exact stdout a real process would have written. Serial by construction:
 * console.log and the cwd are process-global, so two of these interleaved
 * would steal each other's lines.
 */
async function capture(args: readonly string[], fleet: string): Promise<Captured> {
  const prevCwd = process.cwd();
  const prevExit = process.exitCode;
  const origLog = console.log;
  const origErr = console.error;
  let stdout = "";
  console.log = (...parts: unknown[]) => {
    stdout += `${format(...parts)}\n`;
  };
  // stderr is not the payload — a refusal's fix line, a usage diagnostic — so
  // it is swallowed here and the exit code is what reports a failed run.
  console.error = () => undefined;
  process.exitCode = undefined;
  try {
    process.chdir(fleet);
    await buildProgram().parseAsync(["node", "loam", ...args]);
  } finally {
    console.log = origLog;
    console.error = origErr;
    process.chdir(prevCwd);
  }
  const code = typeof process.exitCode === "number" ? process.exitCode : 0;
  process.exitCode = prevExit;
  return { stdout, code };
}

/** The brief's absolute path, in every spelling it can appear in (raw, and JSON-escaped on Windows). */
function normalised(stdout: string, fleet: string): string {
  let out = stdout;
  for (const dir of new Set([fleet, realpathSync(fleet)])) {
    out = out.split(JSON.stringify(dir).slice(1, -1)).join(DOCS_PLACEHOLDER).split(dir).join(DOCS_PLACEHOLDER);
  }
  return out;
}

async function bytesOf(args: readonly string[], fleet = FLEET): Promise<number> {
  const run = await capture(args, fleet);
  if (run.code !== 0) {
    throw new Error(`payload-sizes: \`loam ${args.join(" ")}\` exited ${run.code} — it measured a refusal, not a payload`);
  }
  return Buffer.byteLength(normalised(run.stdout, fleet), "utf8");
}

/**
 * A copy of the example fleet with every text file's line endings as the
 * repository stores them — LF — for the briefs, which are the one row family
 * that quotes the fleet's FILES. The repository carries no `.gitattributes`, so
 * a Windows clone with `core.autocrlf=true` holds the same intent.md with CRLF,
 * and a verbatim intent then escapes one `\r` per line: the default brief rows
 * read 70 bytes larger there than on CI, and the pin failed on the checkout
 * rather than on the numbers (the same reason `committedBlock` reads the page
 * as LF). Removed by the caller.
 */
async function lfFleet(): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), "loam-payload-"));
  await cp(FLEET, dir, { recursive: true });
  for (const entry of await readdir(dir, { recursive: true, withFileTypes: true })) {
    if (!entry.isFile()) continue;
    const file = join(entry.parentPath, entry.name);
    const bytes = await readFile(file);
    if (isUtf8(bytes) && bytes.includes("\r\n")) await writeFile(file, bytes.toString("utf8").replace(/\r\n/g, "\n"));
  }
  return dir;
}

/** `~` tokens as bytes ÷ 4, the usual rough rule for English and code; real tokenizers differ. */
function tokens(bytes: number): string {
  return `~${Math.round(bytes / 4).toLocaleString("en-US")}`;
}

function n(bytes: number): string {
  return bytes.toLocaleString("en-US");
}

/** The invocation as a reader would type it — quoting only what the shell would need. */
function shown(args: readonly string[]): string {
  return `\`loam ${args.map((arg) => (/\s/.test(arg) ? `"${arg}"` : arg)).join(" ")}\``;
}

/**
 * The instruction pages, each invoked the way its slash command passes it —
 * placeholders filled with the example fleet's ids — because an agent loads
 * the filled page, and `$1` is shorter than `FEAT-101`.
 */
const PAGES: readonly (readonly string[])[] = [
  ["loam-adopt", SERVICE],
  ["loam-feature", "FEAT-101", "Split payments"],
  ["loam-implement", "FEAT-101", SERVICE],
  ["loam-check", "FEAT-101"],
  ["loam-verify", "FEAT-101"],
  ["loam-ship", "FEAT-101"],
  ["loam-report"],
  ["loam-codes"],
  ["loam-spine"],
  ["loam-authoring"],
  ["loam-done-check"],
  ["loam-drawing"],
];

/**
 * The three briefs an implementer is handed, as the `loam-implement` page has
 * an agent call them — measured in their default form and with `--intent-ref`,
 * the flag that carries the feature's intent.md by reference. The example
 * fleet's intent is small, so the difference here is small; the module comment
 * of `src/core/document/intent/reference.ts` says what it is on a fleet whose
 * intent is not.
 */
const BRIEFS: readonly (readonly string[])[] = [
  ["tasks", "FEAT-101", "--service", SERVICE, "--next", "--json"],
  ["tasks", "FEAT-101", "--json"],
  ["delta", "FEAT-101", "--service", SERVICE, "--json"],
  ["context", SERVICE, "--feature", "FEAT-101", "--json"],
];

function median(values: readonly number[]): number {
  const sorted = [...values].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 1 ? sorted[mid]! : Math.round((sorted[mid - 1]! + sorted[mid]!) / 2);
}

/** Every code `loam explain --codes --json` lists, and each one's own `explain <code> --json` size. */
async function explainSizes(): Promise<{ count: number; sizes: number[]; vocabulary: number }> {
  const listing = await capture(["explain", "--codes", "--json"], FLEET);
  const codes = (JSON.parse(listing.stdout) as { codes: { code: string }[] }).codes.map((row) => row.code);
  const sizes: number[] = [];
  for (const code of codes) sizes.push(await bytesOf(["explain", code, "--json"]));
  return { count: codes.length, sizes, vocabulary: Buffer.byteLength(listing.stdout, "utf8") };
}

/** One `loam instructions` page, in its three printable forms. */
interface PageSizes {
  readonly args: readonly string[];
  /** As its slash command loads it: no narrowing flag either way. */
  readonly bare: number;
  readonly narrowed: number;
  readonly tabled: number;
}

/** One implementer brief: as called, and with `--intent-ref`. */
interface BriefSizes {
  readonly args: readonly string[];
  readonly bare: number;
  readonly ref: number;
}

/** Everything the block and the payload ceiling read — measured once per run. */
export interface Payloads {
  readonly agents: number;
  readonly brief: number;
  readonly targets: number;
  readonly explained: { count: number; sizes: number[]; vocabulary: number };
  readonly pages: readonly PageSizes[];
  readonly briefs: readonly BriefSizes[];
}

/** Every measurement the block prints, in process — the expensive half, so a test takes it once. */
export async function measurePayloads(): Promise<Payloads> {
  const pages: PageSizes[] = [];
  for (const page of PAGES) {
    pages.push({
      args: page,
      bare: await bytesOf(["instructions", ...page]),
      narrowed: await bytesOf(["instructions", ...page, "--no-fix-tables"]),
      tabled: await bytesOf(["instructions", ...page, "--fix-tables"]),
    });
  }
  const briefs: BriefSizes[] = [];
  const lf = await lfFleet();
  try {
    for (const args of BRIEFS) briefs.push({ args, bare: await bytesOf(args, lf), ref: await bytesOf([...args, "--intent-ref"], lf) });
  } finally {
    await rm(lf, { recursive: true, force: true });
  }
  return {
    agents: Buffer.byteLength(AGENTS_MD, "utf8"),
    brief: await bytesOf(["adopt", "--service", SERVICE, "--json"]),
    targets: await bytesOf(["adopt", "--service", SERVICE, "--json", "--targets"]),
    explained: await explainSizes(),
    pages,
    briefs,
  };
}

/**
 * Every call an agent makes in its DEFAULT form — no flag that narrows or widens
 * what it is handed — with what it costs. What the payload ceiling grades
 * (test/docs-facts.test.ts): a host keeps a tool result inline only up to a
 * size (Claude Code moves an MCP tool result over 50,000 characters into a
 * file), so a default form over it is read in pieces by every agent that
 * takes it.
 *
 * `explain --codes` is here although `--codes` is a flag, because it is the
 * one form of that verb an agent asks for the whole vocabulary with; and the
 * explain row is its LARGEST single answer, since a ceiling is about the worst
 * call rather than the median one.
 */
export function defaultCalls(m: Payloads): Array<{ invocation: string; bytes: number }> {
  return [
    { invocation: "AGENTS.md", bytes: m.agents },
    { invocation: shown(["adopt", "--service", SERVICE, "--json"]), bytes: m.brief },
    { invocation: "`loam explain <code> --json`, the largest", bytes: Math.max(...m.explained.sizes) },
    { invocation: shown(["explain", "--codes", "--json"]), bytes: m.explained.vocabulary },
    ...m.pages.map((page) => ({ invocation: shown(["instructions", ...page.args]), bytes: page.bare })),
    ...m.briefs.map((brief) => ({ invocation: shown(brief.args), bytes: brief.bare })),
  ];
}

/** "same bytes" when a flag changed nothing, else the size it gave. */
function variant(bytes: number, bare: number): string {
  return bytes === bare ? "same bytes" : `${n(bytes)} (${tokens(bytes)})`;
}

/**
 * The generated block, exactly as docs/BENCHMARKS.md carries it between
 * {@link BEGIN} and {@link END}. Deterministic for a given tree: no clock, no
 * machine path, no host fact. The date lives OUTSIDE the block for exactly
 * that reason — the pin compares the tree's numbers, and a regenerated date
 * would make every comparison fail on the calendar instead of on the bytes.
 */
export async function payloadBlock(measured?: Payloads): Promise<string> {
  const m = measured ?? (await measurePayloads());
  const { agents, brief, targets, explained } = m;
  const adoptPage = m.pages[0]!.bare;
  const lines = [
    BEGIN,
    "",
    `loam \`${LOAM_VERSION}\` · fleet \`examples/docs\` · service \`${SERVICE}\` · bytes on stdout, ~tokens = bytes ÷ 4`,
    "",
    "| payload | invocation | bytes | ~tokens |",
    "|---|---|---|---|",
    `| orientation, always loaded | \`AGENTS.md\` as \`loam init --create\` writes it | ${n(agents)} | ${tokens(agents)} |`,
    `| adopt brief | ${shown(["adopt", "--service", SERVICE, "--json"])} | ${n(brief)} | ${tokens(brief)} |`,
    `| adopt brief, per-service part | ${shown(["adopt", "--service", SERVICE, "--json", "--targets"])} | ${n(targets)} | ${tokens(targets)} |`,
    `| an adopt session before it reads code | the \`loam-adopt\` page + the full brief | ${n(adoptPage + brief)} | ${tokens(adoptPage + brief)} |`,
  ];
  const mid = median(explained.sizes);
  const max = Math.max(...explained.sizes);
  const min = Math.min(...explained.sizes);
  lines.push(
    `| one code, median of ${explained.count} | \`loam explain <code> --json\` | ${n(mid)} | ${tokens(mid)} |`,
    `| one code, smallest / largest | \`loam explain <code> --json\` | ${n(min)} / ${n(max)} | ${tokens(min)} / ${tokens(max)} |`,
    `| the whole code vocabulary | ${shown(["explain", "--codes", "--json"])} | ${n(explained.vocabulary)} | ${tokens(explained.vocabulary)} |`,
    "",
    "| page | invocation | bytes | ~tokens | with `--no-fix-tables` | with `--fix-tables` |",
    "|---|---|---|---|---|---|",
  );
  for (const page of m.pages) {
    lines.push(
      `| \`${page.args[0]}\` | ${shown(["instructions", ...page.args])} | ${n(page.bare)} | ${tokens(page.bare)} `
        + `| ${variant(page.narrowed, page.bare)} | ${variant(page.tabled, page.bare)} |`,
    );
  }
  lines.push("", "| brief | invocation | bytes | ~tokens | with `--intent-ref` |", "|---|---|---|---|---|");
  for (const brief of m.briefs) {
    lines.push(`| \`${brief.args[0]}\` | ${shown(brief.args)} | ${n(brief.bare)} | ${tokens(brief.bare)} | ${variant(brief.ref, brief.bare)} |`);
  }
  lines.push("", END);
  return lines.join("\n");
}

/**
 * The committed block, markers included and line endings LF, or null when the
 * page has none. LF because the repository carries no `.gitattributes`: a
 * Windows clone with `core.autocrlf=true` reads the page back with CRLF, and a
 * pin that failed on the line ending would be failing on the checkout, not on
 * the numbers.
 */
export function committedBlock(page: string): string | null {
  const lf = page.replace(/\r\n/g, "\n");
  const start = lf.indexOf(BEGIN);
  const end = lf.indexOf(END);
  if (start === -1 || end === -1 || end < start) return null;
  return lf.slice(start, end + END.length);
}

async function main(): Promise<void> {
  const block = await payloadBlock();
  const mode = process.argv[2];
  if (mode === undefined) {
    console.log(block);
    return;
  }
  const raw = await readFile(PAGE, "utf8");
  const crlf = raw.includes("\r\n");
  const page = raw.replace(/\r\n/g, "\n");
  const committed = committedBlock(page);
  if (committed === null) {
    console.error(`payload-sizes: ${PAGE} carries no ${BEGIN} … ${END} block`);
    process.exitCode = 1;
    return;
  }
  if (mode === "--check") {
    if (committed === block) {
      console.log("payload-sizes: docs/BENCHMARKS.md matches this tree");
      return;
    }
    console.error("payload-sizes: docs/BENCHMARKS.md is behind this tree — run `npx tsx scripts/payload-sizes.ts --write`");
    process.exitCode = 1;
    return;
  }
  if (mode !== "--write") {
    console.error(`payload-sizes: unknown argument '${mode}' — expected --write or --check`);
    process.exitCode = 1;
    return;
  }
  const today = new Date().toISOString().slice(0, 10);
  // Function replacements, not strings: a replacement STRING interprets `$&`
  // and `$1`, and the block quotes command lines a future row may well spell
  // with a dollar sign.
  const dated = page.replace(DATE_LINE, () => `Measured ${today} by \`npx tsx scripts/payload-sizes.ts --write\`.`);
  const fresh = dated.replace(committed, () => block);
  await writeFile(PAGE, crlf ? fresh.replace(/\n/g, "\r\n") : fresh);
  console.log(`payload-sizes: rewrote the block in docs/BENCHMARKS.md (${today})`);
}

/** Run, or merely imported by test/docs-facts.test.ts? Same realpath rule src/cli.ts uses. */
function invokedDirectly(): boolean {
  const entry = process.argv[1];
  if (entry === undefined) return false;
  try {
    return realpathSync(entry) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (invokedDirectly()) await main();
